"""Role-guarded generic CRUD for simple master data. Anything with business rules has a dedicated endpoint instead."""
from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy import text, inspect
from .auth import password_problems, hash_password
from .deps import db, require, STAFF, audit

router = APIRouter(prefix="/api/resources", tags=["resources"])

TABLES = {k: k for k in ("customers", "users", "products", "product_variants", "plans", "discounts", "quotations", "subscriptions",
                         "invoices", "payments", "taxes", "payment_terms", "quotation_templates")}
SEARCH = {"customers": ["name", "email", "company_name"], "products": ["name", "sku"], "plans": ["name"], "discounts": ["code", "name"],
          "quotations": ["quotation_number"], "subscriptions": ["subscription_number"], "invoices": ["invoice_number"],
          "payments": ["payment_number"], "users": ["full_name", "email"], "product_variants": ["attribute", "value"],
          "taxes": ["name"], "payment_terms": ["name"], "quotation_templates": ["name"]}
ADMIN_ONLY_WRITE = {"users", "products", "product_variants", "plans", "discounts", "taxes", "payment_terms", "quotation_templates"}
NO_GENERIC_CREATE = {"invoices": "Invoices are generated by the billing run",
                     "payments": "Use POST /api/payments (it allocates the payment to invoices)",
                     "quotations": "Use POST /api/quotations/from-template"}
NO_DELETE = {"invoices", "payments", "subscriptions", "quotations", "customers"}   # keep financial history; cancel/close instead
PROTECTED = {"*": {"id", "created_at", "updated_at"},
             "users": {"password_hash", "failed_logins", "locked_until", "email_verified_at", "last_login_at", "created_by"},
             "invoices": {"invoice_number", "status", "subtotal", "discount_total", "tax_total", "total", "amount_paid", "amount_due",
                          "paid_at", "confirmed_at", "cancelled_at", "sent_at", "billing_run_id", "subscription_id", "customer_id"},
             "payments": {"payment_number", "amount", "customer_id"},
             "subscriptions": {"subscription_number", "status", "paused_at", "resumed_at", "closed_at", "closure_reason",
                               "renewal_count", "last_billed_through", "quotation_id"},
             "quotations": {"quotation_number", "status", "subtotal", "discount_total", "tax_total", "total", "approved_at", "template_id"}}
USER_SAFE = "id,email,role,full_name,phone,is_active,created_at,updated_at"
FILTERABLE = ("status", "customer_id", "is_active", "product_id", "plan_id")


def _table(resource):
    if resource not in TABLES: raise HTTPException(404, "Unknown resource")
    return TABLES[resource]


@router.get("/{resource}")
def list_resource(resource: str, limit: int = 50, offset: int = 0, q: str | None = None, status: str | None = None,
                  customer_id: int | None = None, plan_id: int | None = None, user=Depends(require(*STAFF))):
    table = _table(resource)
    if resource == "users" and user["role"] != "admin": raise HTTPException(403, "Only the admin can view staff accounts")
    limit = max(1, min(limit, 200)); offset = max(0, offset)
    where, params = [], {}
    if q and SEARCH.get(resource):
        where.append("(" + " OR ".join(f"{col}::text ILIKE :q" for col in SEARCH[resource]) + ")"); params["q"] = f"%{q}%"
    with db().connect() as c:
        cols = {x["name"] for x in inspect(c).get_columns(table)}
        for k, v in (("status", status), ("customer_id", customer_id), ("plan_id", plan_id)):
            if v is not None and k in cols:
                where.append(f"{k}::text = :{k}"); params[k] = str(v)
        w = (" WHERE " + " AND ".join(where)) if where else ""
        sel = f"SELECT {USER_SAFE} FROM users" if table == "users" else f"SELECT * FROM {table}"
        rows = c.execute(text(f"{sel}{w} ORDER BY id DESC LIMIT :lim OFFSET :off"), {**params, "lim": limit, "off": offset}).mappings().all()
        total = c.execute(text(f"SELECT count(*) FROM {table}{w}"), params).scalar()
    return {"items": [dict(r) for r in rows], "total": total, "limit": limit, "offset": offset}


def _clean(table, cols, payload, protected_extra=()):
    blocked = PROTECTED["*"] | PROTECTED.get(table, set()) | set(protected_extra)
    extra = {"password"} if table == "users" else set()
    unknown = [k for k in payload if k not in cols and k not in extra]
    if unknown: raise HTTPException(422, f"Unknown field(s) for {table}: {', '.join(unknown)}")
    bad = [k for k in payload if k in blocked]
    if bad: raise HTTPException(422, f"Field(s) cannot be set directly: {', '.join(bad)}")
    return {k: v for k, v in payload.items() if k in cols and v not in ("", None)}


@router.post("/{resource}", status_code=201)
def create_resource(resource: str, payload: dict, user=Depends(require(*STAFF))):
    table = _table(resource)
    if resource in NO_GENERIC_CREATE: raise HTTPException(405, NO_GENERIC_CREATE[resource])
    if (resource in ADMIN_ONLY_WRITE) and user["role"] != "admin":
        raise HTTPException(403, "Only the admin can create this")
    try:
        with db().begin() as c:
            cols = {x["name"] for x in inspect(c).get_columns(table)}
            data = _clean(table, cols, payload)
            if table == "users":
                pw = payload.get("password"); probs = password_problems(pw or "")
                if probs: raise HTTPException(422, "Password " + ", ".join(probs))
                if data.get("role") not in ("staff", "admin", "customer"): raise HTTPException(422, "Role must be staff, admin or customer")
                data["password_hash"] = hash_password(pw); data["created_by"] = user["id"]
                if "email" in data: data["email"] = data["email"].strip().lower()
            elif "created_by" in cols and "created_by" not in data:
                data["created_by"] = user["id"]
            if not data: raise HTTPException(422, "No valid fields supplied")
            names = list(data)
            row = c.execute(text(f"INSERT INTO {table} ({','.join(names)}) VALUES ({','.join(':' + k for k in names)}) RETURNING *"), data).mappings().one()
            result = dict(row); result.pop("password_hash", None)
            audit(c, user["id"], f"{resource}.create", table, result.get("id"), None, {k: v for k, v in data.items() if k != "password_hash"})
            return result
    except HTTPException: raise
    except Exception as e:
        msg = str(e.orig) if hasattr(e, "orig") else str(e)
        raise HTTPException(409 if "unique" in msg.lower() else 422, msg.splitlines()[0][:300])


@router.patch("/{resource}/{record_id}")
def update_resource(resource: str, record_id: int, payload: dict, user=Depends(require(*STAFF))):
    table = _table(resource)
    if resource in ADMIN_ONLY_WRITE and user["role"] != "admin": raise HTTPException(403, "Only the admin can change this")
    if resource == "payments" and "status" in payload and user["role"] != "admin": raise HTTPException(403, "Only the admin can change a payment's status")
    try:
        with db().begin() as c:
            cols = {x["name"] for x in inspect(c).get_columns(table)}
            data = {}
            for k, v in payload.items():
                if k == "password" and table == "users":
                    probs = password_problems(v or "")
                    if probs: raise HTTPException(422, "Password " + ", ".join(probs))
                    data["password_hash"] = hash_password(v)
            clean = _clean(table, cols, {k: v for k, v in payload.items() if k != "password"}, ())
            data.update(clean)
            if not data: raise HTTPException(422, "No valid fields supplied")
            sets = ",".join(f"{k}=:{k}" for k in data); data["rid"] = record_id
            row = c.execute(text(f"UPDATE {table} SET {sets} WHERE id=:rid RETURNING *"), data).mappings().first()
            if not row: raise HTTPException(404, "Record not found")
            result = dict(row); result.pop("password_hash", None)
            audit(c, user["id"], f"{resource}.update", table, record_id, None, {k: v for k, v in data.items() if k not in ("password_hash", "rid")})
            return result
    except HTTPException: raise
    except Exception as e:
        raise HTTPException(422, str(getattr(e, "orig", e)).splitlines()[0][:300])


@router.delete("/{resource}/{record_id}")
def delete_resource(resource: str, record_id: int, user=Depends(require("admin"))):
    table = _table(resource)
    if resource in NO_DELETE: raise HTTPException(405, "This record type is kept for the audit trail - cancel or close it instead")
    try:
        with db().begin() as c:
            if not c.execute(text(f"DELETE FROM {table} WHERE id=:id"), {"id": record_id}).rowcount: raise HTTPException(404, "Record not found")
            audit(c, user["id"], f"{resource}.delete", table, record_id)
            return {"deleted": True, "id": record_id}
    except HTTPException: raise
    except Exception as e:
        raise HTTPException(409, "Cannot delete: other records depend on it (deactivate it instead)")
